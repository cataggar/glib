        \\#define GLIB_SYSDEF_POLLNVAL =32
        \\
        \\#define G_MODULE_SUFFIX "so"
        \\
        \\typedef int GPid;
        \\#define G_PID_FORMAT "i"
        \\
        \\#define GLIB_SYSDEF_AF_UNIX 1
        \\#define GLIB_SYSDEF_AF_INET 2
        \\#define GLIB_SYSDEF_AF_INET6 10
        \\
        \\#define GLIB_SYSDEF_MSG_OOB 1
        \\#define GLIB_SYSDEF_MSG_PEEK 2
        \\#define GLIB_SYSDEF_MSG_DONTROUTE 4
        \\
        \\#define G_DIR_SEPARATOR '/'
        \\#define G_DIR_SEPARATOR_S "/"
        \\#define G_SEARCHPATH_SEPARATOR ':'
        \\#define G_SEARCHPATH_SEPARATOR_S ":"
        \\
        \\G_END_DECLS
        \\
        \\#endif /* __GLIBCONFIG_H__ */
        \\
    );

    // Hand-written stand-in for glib's config.h (normally generated by
    // meson from ~150 compiler probes across the whole glib/gobject/gio
    // tree). Only a conservative subset relevant to the core glib_sources
    // above is set; every HAVE_* symbol not listed here is guarded by an
    // #ifdef with a working (if sometimes slower or less featureful)
    // fallback in the source, so leaving them undefined is safe.
    _ = write_files.add("config.h",
        \\#ifndef __CONFIG_H__
        \\#define __CONFIG_H__
        \\
        \\#define PACKAGE_NAME "glib"
        \\#define PACKAGE_VERSION "2.89.1"
        \\#define GETTEXT_PACKAGE "glib20"
        \\#define GLIB_LOCALE_DIR "/usr/share/locale"
        \\
        \\#define GLIB_INTERFACE_AGE 0
        \\#define GLIB_BINARY_AGE 8901
        \\
        \\// glibc ships a real, working gettext as part of libc itself
        \\// (unlike mingw), so enable it here rather than faking out
        \\// libintl.h with no-op macros (which would also conflict with
        \\// libintl.h's own real declarations when both are included).
        \\#define ENABLE_NLS 1
        \\#define HAVE_BIND_TEXTDOMAIN_CODESET 1
        \\
        \\// Modern glibc's vsnprintf/snprintf/printf are already C99/POSIX
        \\// compliant, so use them directly instead of bundling gnulib's
        \\// vasnprintf-based reimplementation (glib/gnulib/, not compiled
        \\// by this build.zig at all).
        \\#define USE_SYSTEM_PRINTF 1
        \\
        \\#define SIZEOF_CHAR 1
        \\#define SIZEOF_SHORT 2
        \\#define SIZEOF_INT 4
        \\#define SIZEOF_LONG 8
        \\#define SIZEOF_LONG_LONG 8
        \\#define SIZEOF_VOID_P 8
        \\#define SIZEOF_SIZE_T 8
        \\#define SIZEOF_SSIZE_T 8
        \\#define SIZEOF_PTRDIFF_T 8
        \\#define SIZEOF_WCHAR_T 4
        \\#define SIZEOF_TIME_T 8
        \\
        \\#define THREADS_POSIX 1
        \\
        \\#define HAVE_STDINT_H 1
        \\#define HAVE_INTTYPES_H 1
        \\#define HAVE_UNISTD_H 1
        \\#define HAVE_SYS_TYPES_H 1
        \\#define HAVE_SYS_TIME_H 1
        \\#define HAVE_SYS_SELECT_H 1
        \\#define HAVE_SYS_RESOURCE_H 1
        \\#define HAVE_SYS_PRCTL_H 1
        \\#define HAVE_SYS_PARAM_H 1
        \\#define HAVE_SYS_AUXV_H 1
        \\#define HAVE_DIRENT_H 1
        \\#define HAVE_POLL_H 1
        \\#define HAVE_SCHED_H 1
        \\#define HAVE_FTW_H 1
        \\#define HAVE_STDATOMIC_H 1
        \\
        \\#define HAVE_ICONV 1
        \\#define HAVE_LANGINFO_CODESET 1
        \\#define HAVE_CODESET 1
        \\#define HAVE_SETLOCALE 1
        \\
        \\#define HAVE_POLL 1
        \\#define HAVE_PPOLL 1
        \\#define HAVE_MMAP 1
        \\#define HAVE_GETAUXVAL 1
        \\#define HAVE_GETRESUID 1
        \\#define HAVE_GETPWUID_R 1
        \\#define HAVE_GETPWNAM_R 1
        \\
        \\#define HAVE_LOCALTIME_R 1
        \\#define HAVE_GMTIME_R 1
        \\#define HAVE_TIMEGM 1
        \\
        \\#define HAVE_VASPRINTF 1
        \\#define HAVE_STPCPY 1
        \\#define HAVE_STRCASECMP 1
        \\#define HAVE_STRNCASECMP 1
        \\#define HAVE_STRSIGNAL 1
        \\#define HAVE_STRERROR_R 1
        \\#define STRERROR_R_CHAR_P 1
        \\#define HAVE_MEMMEM 1
        \\
        \\#define HAVE_POSIX_MEMALIGN 1
        \\#define HAVE_FSYNC 1
        \\#define HAVE_EVENTFD 1
        \\#define HAVE_O_CLOEXEC 1
        \\#define HAVE_SOCK_CLOEXEC 1
        \\#define HAVE_POSIX_SPAWN 1
        \\#define HAVE_SPAWN_H 1
        \\
        \\#define HAVE_PTHREAD_ATTR_SETSTACKSIZE 1
        \\#define HAVE_PTHREAD_CONDATTR_SETCLOCK 1
        \\#define HAVE_PTHREAD_SETNAME_NP_WITH_TID 1
        \\#define HAVE_PTHREAD_GETNAME_NP 1
        \\#define HAVE_CLOCK_NANOSLEEP 1
        \\#define HAVE_PTHREAD_GETAFFINITY_NP 1
        \\
        \\#define HAVE_STRUCT_TM_TM_GMTOFF 1
        \\
        \\#define G_HAVE_GNUC_VISIBILITY 1
        \\
        \\#endif /* __CONFIG_H__ */
        \\
    );

    const generated_headers = write_files.getDirectory();

    // Generated via glib's own tools/gen-visibility-macros.py (same
    // generator meson uses), so these two headers are exact, not
    // hand-approximated like config.h/glibconfig.h above. Requires
    // `python` on PATH at build time.
    const gen_script = b.path("tools/gen-visibility-macros.py");

    const gen_versions = b.addSystemCommand(&.{ "python", "-B" });
    gen_versions.addFileArg(gen_script);
    gen_versions.addArgs(&.{ "2.89.1", "versions-macros" });
    gen_versions.addFileArg(b.path("glib/gversionmacros.h.in"));
    const gversionmacros_h = gen_versions.addOutputFileArg("gversionmacros.h");

    const gen_visibility = b.addSystemCommand(&.{ "python", "-B" });
    gen_visibility.addFileArg(gen_script);
    gen_visibility.addArgs(&.{ "2.89.1", "visibility-macros", "GLIB" });
    const glib_visibility_h = gen_visibility.addOutputFileArg("glib-visibility.h");

    const mod = b.createModule(.{
        .target = target,
        .optimize = optimize,
        .link_libc = true,
    });
    mod.addIncludePath(generated_headers);
    mod.addIncludePath(b.path("glib"));
    // Consumers include e.g. <glib/gtypes.h>, so the parent of glib/ needs
    // to be on the include path too (matches meson's glibinc).
    mod.addIncludePath(b.path("."));
    mod.addCMacro("HAVE_CONFIG_H", "1");
    mod.addCMacro("GLIB_COMPILATION", "1");
    mod.addCMacro("G_LOG_DOMAIN", "\"GLib\"");
    mod.addCMacro("GLIB_CHARSETALIAS_DIR", "\"\"");
    // Needed for glibc GNU extensions used unconditionally by the sources
    // below: ppoll() (gmain.c), the char*-returning strerror_r()
    // (gbacktrace.c/gstrfuncs.c), etc.
    mod.addCMacro("_GNU_SOURCE", "1");

    // gversionmacros.h/glib-visibility.h are #included (as
    // "gversionmacros.h") from glib/gmacros.h et al, so they need to live
    // next to the other glib/*.h headers on the include path; addCopyFile
    // them into the same generated-headers directory used above.
    // Placed under a "glib/" subdirectory since e.g. gtypes.h includes
    // them as <glib/gversionmacros.h> / <glib/glib-visibility.h>.
    const glib_headers_dir = b.addNamedWriteFiles("glib-generated-headers");
    _ = glib_headers_dir.addCopyFile(gversionmacros_h, "glib/gversionmacros.h");
    _ = glib_headers_dir.addCopyFile(glib_visibility_h, "glib/glib-visibility.h");
    mod.addIncludePath(glib_headers_dir.getDirectory());

    mod.addCSourceFiles(.{
        .root = b.path("glib"),
        .files = &glib_core_sources,
        .flags = &.{"-std=gnu99"},
    });

    const lib = b.addLibrary(.{
        .name = "glib-2.0",
        .linkage = .static,
        .root_module = mod,
    });
    b.installArtifact(lib);

    // Install headers so zig-out/include is directly usable by a
    // consumer: <glib.h> plus every glib/*.h (galloca.h, garray.h, ...)
    // under zig-out/include/glib/, and the hand-written/generated headers
    // that normally live in meson's separate config/glibinc dirs.
    lib.installHeader(b.path("glib/glib.h"), "glib.h");
    b.installDirectory(.{
        .source_dir = b.path("glib"),
        .install_dir = .header,
        .install_subdir = "glib",
        .include_extensions = &.{".h"},
    });
    lib.installHeader(generated_headers.join(b.allocator, "glibconfig.h") catch @panic("OOM"), "glibconfig.h");
    lib.installHeader(gversionmacros_h, "glib/gversionmacros.h");
    lib.installHeader(glib_visibility_h, "glib/glib-visibility.h");
}
