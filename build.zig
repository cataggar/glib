pub fn build(b: *std.Build) void {
    const target = b.standardTargetOptions(.{});
    const optimize = b.standardOptimizeOption(.{});

    if (target.result.os.tag != .linux) {
        std.debug.print(
            "warning: this build.zig has only been verified against Linux glibc targets; " ++
                "Windows/macOS need extra work (iconv/gettext shims), see comments in build.zig\n",
            .{},
        );
    }

    const write_files = b.addWriteFiles();

    // Hand-written stand-in for glib/glibconfig.h (normally generated by
    // meson from glibconfig.h.in via extensive compiler probing). Values
    // below are hardcoded for a 64-bit little-endian Linux (LP64) target.
    _ = write_files.add("glibconfig.h",
        \\#ifndef __GLIBCONFIG_H__
        \\#define __GLIBCONFIG_H__
        \\
        \\#include <glib/gmacros.h>
        \\#include <limits.h>
        \\#include <float.h>
        \\
        \\#define GLIB_USING_SYSTEM_PRINTF 1
        \\
        \\G_BEGIN_DECLS
        \\
        \\#define G_MINFLOAT    FLT_MIN
        \\#define G_MAXFLOAT    FLT_MAX
        \\#define G_MINDOUBLE    DBL_MIN
        \\#define G_MAXDOUBLE    DBL_MAX
        \\#define G_MINSHORT    SHRT_MIN
        \\#define G_MAXSHORT    SHRT_MAX
        \\#define G_MAXUSHORT    USHRT_MAX
        \\#define G_MININT    INT_MIN
        \\#define G_MAXINT    INT_MAX
        \\#define G_MAXUINT    UINT_MAX
        \\#define G_MINLONG    LONG_MIN
        \\#define G_MAXLONG    LONG_MAX
        \\#define G_MAXULONG    ULONG_MAX
        \\
        \\typedef signed char gint8;
        \\typedef unsigned char guint8;
        \\
        \\typedef signed short gint16;
        \\typedef unsigned short guint16;
        \\
        \\#define G_GINT16_MODIFIER "h"
        \\#define G_GINT16_FORMAT "hi"
        \\#define G_GUINT16_FORMAT "hu"
        \\
        \\typedef signed int gint32;
        \\typedef unsigned int guint32;
        \\
        \\#define G_GINT32_MODIFIER ""
        \\#define G_GINT32_FORMAT "i"
        \\#define G_GUINT32_FORMAT "u"
        \\
        \\#define G_HAVE_GINT64 1
        \\
        \\typedef signed long gint64;
        \\typedef unsigned long guint64;
        \\
        \\#define G_GINT64_CONSTANT(val)    (val##L)
        \\#define G_GUINT64_CONSTANT(val)    (val##UL)
        \\
        \\#define G_GINT64_MODIFIER "l"
        \\#define G_GINT64_FORMAT "li"
        \\#define G_GUINT64_FORMAT "lu"
        \\
        \\#define GLIB_SIZEOF_VOID_P 8
        \\#define GLIB_SIZEOF_LONG   8
        \\#define GLIB_SIZEOF_SIZE_T 8
        \\#define GLIB_SIZEOF_SSIZE_T 8
        \\
        \\typedef signed long gssize;
        \\typedef unsigned long gsize;
        \\#define G_GSIZE_MODIFIER "l"
        \\#define G_GSSIZE_MODIFIER "l"
        \\#define G_GSIZE_FORMAT "lu"
        \\#define G_GSSIZE_FORMAT "li"
        \\
        \\#define G_MAXSIZE    G_MAXULONG
        \\#define G_MINSSIZE    G_MINLONG
        \\#define G_MAXSSIZE    G_MAXLONG
        \\
        \\typedef gint64 goffset;
        \\#define G_MINOFFSET    G_MININT64
        \\#define G_MAXOFFSET    G_MAXINT64
        \\
        \\#define G_GOFFSET_MODIFIER      G_GINT64_MODIFIER
        \\#define G_GOFFSET_FORMAT        G_GINT64_FORMAT
        \\#define G_GOFFSET_CONSTANT(val) G_GINT64_CONSTANT(val)
        \\
        \\#define G_POLLFD_FORMAT "%d"
        \\
        \\#define GPOINTER_TO_INT(p)    ((gint)  (glong) (p))
        \\#define GPOINTER_TO_UINT(p)    ((guint) (gulong) (p))
        \\
        \\#define GINT_TO_POINTER(i)    ((gpointer) (glong) (i))
        \\#define GUINT_TO_POINTER(u)    ((gpointer) (gulong) (u))
        \\
        \\typedef signed long gintptr;
        \\typedef unsigned long guintptr;
        \\
        \\#define G_GINTPTR_MODIFIER      "l"
        \\#define G_GINTPTR_FORMAT        "li"
        \\#define G_GUINTPTR_FORMAT       "lu"
        \\
        \\#define GLIB_MAJOR_VERSION 2
        \\#define GLIB_MINOR_VERSION 89
        \\#define GLIB_MICRO_VERSION 1
        \\
        \\#define G_OS_UNIX
